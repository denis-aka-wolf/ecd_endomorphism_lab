# БЛОК 2: P-АДИЧЕСКИЙ АНАЛИЗ ФОРМАЛЬНОЙ ГРУППЫ КРИВОЙ COBLITZ
# =====================================================================
def formal_group_addition(z1, z2, p, prec):
    """
    Локальный закон сложения в окрестности бесконечности эллиптической кривой.
    Моделирует гомоморфизм сложения в p-адическом кольце.
    """
    modulus = p ** prec
    B = 7
    sum_linear = z1 + z2
    correction = -4 * B * z1 * z2 * (z1**4 + z2**4)
    return (sum_linear + correction) % modulus

def p_adic_log(z, p, prec):
    """
    Вычисляет p-адический логарифм формальной группы (Ряд Ивасавы).
    z должно быть кратно p (принадлежать ядру редукции).
    """
    if z % p != 0:
        raise ValueError("Критическая ошибка: параметр z должен делиться на p!")
    modulus = p ** prec
    total_sum = z
    B = 7
    if prec > 1:
        numerator = -4 * B * (z ** 7)
        denominator = 7
        if denominator % p != 0:
            inv_den = pow(denominator, -1, modulus)
            total_sum += numerator * inv_den
        else:
            total_sum += (numerator // p) * pow(denominator // p, -1, modulus)
    return total_sum % modulus

