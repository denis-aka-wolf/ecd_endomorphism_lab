# БЛОК 3: АЛГЕБРАИЧЕСКИЙ КОНТУР СЕМАЕВА (INDEX CALCULUS BASE)
# =====================================================================
def semaev_f3(x1, x2, x3):
    """
    Вычисляет значение 3-го полинома Семаева для кривой y^2 = x^3 + 7 по модулю P.
    f3(x1, x2, x3) == 0 тогда и только тогда, когда P1 + P2 +- P3 = O.
    Используется для исключения групповой геометрии и перехода к алгебраическим системам.
    """
    p = SECP256K1_P
    
    # Симметрические компоненты уравнения Семаева, адаптированные под A=0, B=7
    term1 = (pow(x1 - x2, 2, p) * pow(x3, 2, p)) % p
    term2 = (2 * (x1 * x2 * (x1 + x2) + 14) * x3) % p
    term3 = (pow(x1 * x2, 2, p) - 28 * (x1 + x2)) % p
    
    return (term1 - term2 + term3) % p

