# =====================================================================
# ОФИЦИАЛЬНЫЕ МАТЕМАТИЧЕСКИЕ КОНСТАНТЫ КРИВОЙ SECP256K1 (BITCOIN)
# =====================================================================
SECP256K1_P = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F
SECP256K1_N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
SECP256K1_LAMBDA = 0x5363ad4cc05c30e0a5261c028812645a122e22ea20816678df02967c1b23bd72

# =====================================================================
# БЛОК 1: ДИНАМИЧЕСКОЕ GLV-РАЗЛОЖЕНИЕ (АЛГОРИТМ ЕВКЛИДА)
# =====================================================================
def glv_decompose_euclidean(k):
    """
    Абсолютно стабильное GLV-разложение через расширенный алгоритм Евклида.
    Вычисляет k1, k2 такие, что k = k1 + k2 * LAMBDA (mod n).
    Размерность k1, k2 гарантированно снижается до ~128 бит.
    """
    n = SECP256K1_N
    k = k % n
    
    # Шаг 1: Находим укороченные базисные векторы через деление Евклида
    r0, r1 = n, SECP256K1_LAMBDA
    t0, t1 = 0, 1
    
    # Остановка, когда остаток падает ниже границы sqrt(n) (2^128)
    limit = 1 << 128
    
    while r1 >= limit:
        q = r0 // r1
        r0, r1 = r1, r0 - q * r1
        t0, t1 = t1, t0 - q * t1
        
    # Базисные векторы решетки ГЛВ
    v1_x, v1_y = r0, -t0
    v2_x, v2_y = r1, -t1
    
    # Шаг 2: Алгоритм Бабера для нахождения кратчайшего вектора
    det = v1_x * v2_y - v1_y * v2_x
    
    c1 = (k * v2_y + (det // 2 if det > 0 else -det // 2)) // det
    c2 = (-k * v1_y + (det // 2 if det > 0 else -det // 2)) // det
    
    # Вычисление сбалансированных скаляров
    k1 = (k - c1 * v1_x - c2 * v2_x) % n
    k2 = (-c1 * v1_y - c2 * v2_y) % n
    
    # Приведение к знаковым полуинтервалам [-n//2, n//2]
    if k1 > n // 2:
        k1 -= n
    if k2 > n // 2:
        k2 -= n
        
    return k1, k2

