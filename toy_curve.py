# БЛОК 2: P-АДИЧЕСКИЙ АНАЛИЗ ФОРМАЛЬНОЙ ГРУППЫ КРИВОЙ COBLITZ
# =====================================================================
def formal_group_addition(z1, z2, p, prec):
    modulus = p ** prec
    B = 7
    sum_linear = z1 + z2
    correction = -4 * B * z1 * z2 * (z1**4 + z2**4)
    return (sum_linear + correction) % modulus

def p_adic_log(z, p, prec):
    if z % p != 0:
        raise ValueError("Критическая ошибка: параметр z должен делиться на p!")
    modulus = p ** prec
    total_sum = z
    B = 7
    if prec > 1:
        numerator = -4 * B * (z ** 7)
        denominator = 7
        if denominator % p != 0:
            inv_den = pow(denominator, -1, modulus)
            total_sum += numerator * inv_den
        else:
            total_sum += (numerator // p) * pow(denominator // p, -1, modulus)
    return total_sum % modulus

# =====================================================================
# БЛОК 3: АЛГЕБРАИЧЕСКИЙ КОНТУР СЕМАЕВА (INDEX CALCULUS BASE)
# =====================================================================
def semaev_f3(x1, x2, x3, p_modulus):
    """Вычисляет значение 3-го полинома Семаева для y^2 = x^3 + 7."""
    p = p_modulus
    term1 = (pow(x1 - x2, 2, p) * pow(x3, 2, p)) % p
    term2 = (2 * (x1 * x2 * (x1 + x2) + 14) * x3) % p
    term3 = (pow(x1 * x2, 2, p) - 28 * (x1 + x2)) % p
    return (term1 - term2 + term3) % p

# =====================================================================
# БЛОК 6: АЛГЕБРАИЧЕСКИЙ СОЛВЕР ДЛЯ ИГРУШЕЧНОЙ МОДЕЛИ
# =====================================================================
def solve_toy_system(x_P, x_Q, p_modulus):
    """
    Алгебраический решатель. Находит все возможные координаты x_X промежуточной точки,
    удовлетворяющие уравнению Семаева f3(x_P, x_X, x_Q) == 0 mod P.
    Это исключает полный геометрический перебор точек на кривой.
    """
    solutions = []
    # Для 16-битного поля мы можем быстро найти корни полинома.
    # В полноценном Index Calculus здесь применяется алгоритм Берлекэмпа-Рабиновича.
    for x_candidate in range(p_modulus):
        if semaev_f3(x_P, x_candidate, x_Q, p_modulus) == 0:
            solutions.append(x_candidate)
    return solutions

