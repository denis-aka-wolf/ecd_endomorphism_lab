# =====================================================================
# БЛОК 1: ДИНАМИЧЕСКОЕ GLV-РАЗЛОЖЕНИЕ (АЛГОРИТМ ЕВКЛИДА)
# =====================================================================
def glv_decompose_euclidean(k, n_modulus, lambda_val):
    """
    Стабильное GLV-разложение через расширенный алгоритм Евклида.
    Работает инвариантно как для secp256k1, так и для малых toy-кривых.
    """
    n = n_modulus
    k = k % n
    
    r0, r1 = n, lambda_val
    t0, t1 = 0, 1
    
    # Динамическая граница переключения в зависимости от размера порядка группы
    limit = int(n ** 0.5) + 1
    
    while r1 >= limit:
        q = r0 // r1
        r0, r1 = r1, r0 - q * r1
        t0, t1 = t1, t0 - q * t1
        
    v1_x, v1_y = r0, -t0
    v2_x, v2_y = r1, -t1
    
    det = v1_x * v2_y - v1_y * v2_x
    
    c1 = (k * v2_y + (det // 2 if det > 0 else -det // 2)) // det
    c2 = (-k * v1_y + (det // 2 if det > 0 else -det // 2)) // det
    
    k1 = (k - c1 * v1_x - c2 * v2_x) % n
    k2 = (-c1 * v1_y - c2 * v2_y) % n
    
    if k1 > n // 2: k1 -= n
    if k2 > n // 2: k2 -= n
        
    return k1, k2

