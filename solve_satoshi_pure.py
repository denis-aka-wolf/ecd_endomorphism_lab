import sys

# Параметры поля secp256k1 и коэффициенты из вашего .anf файла
P = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F

A = 0x2281e25a6598881f570f10ef03294c03fd46018ac75af0a1092db5fb5f1b750b
B = 0x3b9364a918ebb5452f0911328b1782d67d6926206dfb9631d49fd3436f021702
C = 0x38ed0bc25afd20a3003eda4fc3dfd1d1f5ed491d8e062d60b91bf35c04f8a494

def modular_sqrt(a, p):
    """
    Извлекает квадратный корень из 'a' по модулю простого числа 'p'.
    Для поля secp256k1 (где P % 4 == 3) работает мгновенное тождество:
    корень = a^((p+1)//4) mod p. Это заменяет тяжелый алгоритм Тонелли-Шенкса.
    """
    # Проверяем, является ли число квадратичным вычетом (Критерий Эйлера)
    if pow(a, (p - 1) // 2, p) != 1:
        return None  # Квадратного корня в этом поле не существует
    return pow(a, (p + 1) // 4, p)

def solve_quadratic_modular():
    print("=== ПОИСК КОРНЕЙ КВАДРАТНОГО ПОЛИНОМА СЕМАЕВА (ЧИСТЫЙ PYTHON) ===")
    print("Цель: Поиск корней полинома Семаева Сатоши Накамото...\n")
    
    # Классический дискриминант: D = B^2 - 4*A*C (mod P)
    D = (pow(B, 2, P) - 4 * A * C) % P
    
    # Извлекаем модульный квадратный корень из дискриминанта
    sqrt_D = modular_sqrt(D, P)
    
    if sqrt_D is None:
        print("[Результат]: Дискриминант D не является квадратичным вычетом по модулю P.")
        print("             Уравнение данного порядка (f3) не имеет корней в базовом поле GF(P).")
        print("             Следствие: Промежуточная точка лежит в расширении поля, либо")
        print("             требуется построение многочлена Семаева высшего порядка (f4).")
        return
        
    # Вычисляем модульную инверсию для делителя (2 * A)^(-1) mod P
    inv_2A = pow(2 * A, -1, P)
        
    # Находим два корня по модульной формуле: x = (-B +- sqrt(D)) * (2*A)^(-1) mod P
    x1 = ((-B + sqrt_D) * inv_2A) % P
    x2 = ((-B - sqrt_D) * inv_2A) % P
    
    print(f"[УСПЕХ]: Найдено 2 истинных алгебраических корня системы:")
    print(f" -> x1 = {hex(x1)}")
    print(f" -> x2 = {hex(x2)}")

if __name__ == "__main__":
    solve_quadratic_modular()
